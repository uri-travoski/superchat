import { chromium } from "playwright-core";
import fs from "fs";
const exe = fs.readdirSync(process.env.HOME + "/.cache/ms-playwright").filter(d=>d.startsWith("chromium-")).sort().pop();
const base = process.env.HOME + "/.cache/ms-playwright/" + exe;
const sub = "chrome-linux64";
const b = await chromium.launch({ executablePath: `${base}/${sub}/chrome`, args: ["--no-sandbox"] });
const p = await b.newPage({ viewport: { width: 1200, height: 800 } });
p.on("response", r => { if (r.status()>=400) console.log("HTTP", r.status(), r.url()); });
p.on("console", m => { if (m.type()==="error") console.log("console error:", m.text()); });
p.on("pageerror", e => console.log("pageerror:", e.message));
const shot = (n) => p.screenshot({ path: `/tmp/claude-1000/uitest/${n}.png` });
await p.goto("http://127.0.0.1:18301/admin/");
