#!/usr/bin/env python3
"""Extracts the picker emoji as 64x64 PNGs from Noto Color Emoji (SIL OFL 1.1) and writes
apps/desktop/src/emoji_data.rs (include_bytes! table). Needs: pip install fonttools pillow.
The software and femtovg renderers draw colour-bitmap fonts as outlines, so the UI shows these images instead.
Usage: tools/gen_emoji.py [path to NotoColorEmoji.ttf]"""
import io, re, sys, os
from fontTools.ttLib import TTFont
from PIL import Image

root = os.path.join(os.path.dirname(__file__), "..")
font = TTFont(sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/truetype/noto/NotoColorEmoji.ttf")
src = open(os.path.join(root, "crates/client-core/src/logic/emoji.rs")).read()
emojis = []
def unesc(t):
    return re.sub(r"\\u\{([0-9A-Fa-f]+)\}", lambda m: chr(int(m.group(1), 16)), t)
for g in re.findall(r'"([^"]+)"', src):
    g = unesc(g)
    if any(ord(c) > 0x2000 for c in g):
        emojis += g.split(" ")
# also the quick reactions and anything else the app uses
cmap = font.getBestCmap()
gsets = font["GSUB"].table if "GSUB" in font else None
cbdt = font["CBDT"]
strike = cbdt.strikeData[0]
glyph_order = font.getGlyphOrder()

def glyph_for(e):
    cps = [ord(c) for c in e if ord(c) not in (0xFE0F,)]
    if len(cps) == 1:
        return cmap.get(cps[0])
    # sequences (ZWJ, skin tones) live in GSUB ligatures: try the composed glyph name
    names = [cmap.get(c) for c in cps]
    return None

# Ligature table for sequences
lig = {}
if gsets:
    for lookup in gsets.LookupList.Lookup:
        for st in lookup.SubTable:
            st = getattr(st, "ExtSubTable", st)
            if hasattr(st, "ligatures"):
                for first, ls in st.ligatures.items():
                    for l in ls:
                        lig[tuple([first] + list(l.Component))] = l.LigGlyph

out = os.path.join(root, "apps/desktop/emoji")
os.makedirs(out, exist_ok=True)
rows = []
seen = set()
for e in emojis:
    if e in seen:
        continue
    seen.add(e)
    cps = [ord(c) for c in e if ord(c) != 0xFE0F]
    g = cmap.get(cps[0]) if len(cps) == 1 else lig.get(tuple(cmap.get(c) for c in cps))
    if g is None or g not in strike:
        print("missing", e, file=sys.stderr)
        continue
    data = strike[g].imageData
    im = Image.open(io.BytesIO(data)).convert("RGBA").resize((64, 64), Image.LANCZOS)
    name = "-".join("%x" % c for c in cps) + ".png"
    im.save(os.path.join(out, name), optimize=True)
    rows.append((e, name))
with open(os.path.join(root, "apps/desktop/src/emoji_data.rs"), "w") as f:
    f.write("// Generated by tools/gen_emoji.py from Noto Color Emoji (SIL OFL 1.1). Do not edit.\n")
    f.write("pub static EMOJI_PNG: &[(&str, &[u8])] = &[\n")
    for e, name in rows:
        f.write('    ("%s", include_bytes!("../emoji/%s")),\n' % (e, name))
    f.write("];\n")
print(len(rows), "emoji written")
